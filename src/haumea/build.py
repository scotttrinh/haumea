"""Emit a Vercel Build Output API (v3) directory for a Haumea project.

    .vercel/output/
    ├── config.json              rewrites for dynamic routes and /docs
    ├── static/                  public/, plus openapi.json and docs.html
    └── functions/
        ├── index.func/                   one function per route.py
        ├── api/hello.func/
        └── api/items/[item_id].func/
            ├── .vc-config.json
            ├── vc__handler__python.py    trampoline into vercel-runtime
            ├── index.py                  exposes this route's ASGI ``app``
            ├── app/ ...                  project source
            └── _vendor/                  dependencies for the target platform

Every function carries the same source and dependencies (hard-linked on disk)
and differs only in its entrypoint and ``.vc-config.json``. The function
layout mirrors what Vercel's own Python builder produces.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import tempfile
from pathlib import Path

from fastapi.openapi.docs import get_swagger_ui_html

from haumea.routing import Route, create_app, discover_routes

OUTPUT_DIR = Path(".vercel") / "output"
VENDOR_DIR = "_vendor"
HANDLER_MODULE = "vc__handler__python"
ENTRYPOINT = "index.py"

# Vercel's Python functions run on Amazon Linux 2023 (glibc 2.34).
DEFAULT_PLATFORM = "x86_64-manylinux_2_28"
DEFAULT_PYTHON = "3.12"

IGNORE = shutil.ignore_patterns(
    ".*", "__pycache__", "*.pyc", "public", "node_modules", "tests", "uv.lock"
)

ENTRYPOINT_SOURCE = """\
import os

from haumea import create_route_app

app = create_route_app(os.path.join(os.path.dirname(__file__), "app"), {function!r})
"""

# Module-level settings a route.py may define, and their .vc-config.json keys.
ROUTE_CONFIG = {"max_duration": "maxDuration", "memory": "memory", "regions": "regions"}

# Same contract as the trampoline generated by @vercel/python: point
# vercel-runtime at our entrypoint, put vendored deps on sys.path, hand over.
TRAMPOLINE_SOURCE = f"""\
import importlib
import os
import site
import sys
import time

_here = os.path.dirname(__file__)

os.environ.update({{
    "__VC_PY_BOOT_START_MS": str(int(time.monotonic() * 1000)),
    "__VC_HANDLER_MODULE_NAME": "index",
    "__VC_HANDLER_ENTRYPOINT": "{ENTRYPOINT}",
    "__VC_HANDLER_ENTRYPOINT_ABS": os.path.join(_here, "{ENTRYPOINT}"),
    "__VC_HANDLER_VENDOR_DIR": "{VENDOR_DIR}",
    "__VC_HANDLER_VARIABLE_NAME": "app",
}})

_vendor = os.path.join(_here, "{VENDOR_DIR}")
site.addsitedir(_vendor)
while _vendor in sys.path:
    sys.path.remove(_vendor)
sys.path.insert(1 if sys.path and sys.path[0] in ("", _here) else 0, _vendor)
importlib.invalidate_caches()

from vercel_runtime.vc_init import vc_handler  # noqa: E402,F401
"""


def _run(cmd: list[str], cwd: Path) -> None:
    result = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"`{' '.join(cmd)}` failed:\n{result.stderr}")


def _install_dependencies(
    project_dir: Path, vendor_dir: Path, python: str, platform: str | None
) -> None:
    """Vendor the project's locked dependencies plus Vercel's Python runtime."""
    with tempfile.TemporaryDirectory() as tmp:
        requirements = Path(tmp) / "requirements.txt"
        _run(
            [
                "uv",
                "export",
                "--no-dev",
                "--no-emit-project",
                "--no-editable",
                "--no-hashes",
                "--quiet",
                "-o",
                str(requirements),
            ],
            cwd=project_dir,
        )
        cmd = [
            "uv",
            "pip",
            "install",
            "--quiet",
            "--target",
            str(vendor_dir),
            "--python-version",
            python,
            "-r",
            str(requirements),
            "vercel-runtime",
        ]
        if platform:
            cmd += ["--python-platform", platform]
        _run(cmd, cwd=project_dir)


def _write_function(
    route: Route, shared: Path, functions_dir: Path, python: str
) -> None:
    func_dir = functions_dir / f"{route.function}.func"
    func_dir.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(shared, func_dir, copy_function=os.link)

    module = route.load()
    config = {
        "runtime": f"python{python}",
        "handler": f"{HANDLER_MODULE}.vc_handler",
        "supportsResponseStreaming": True,
        "environment": {"PYTHONDONTWRITEBYTECODE": "1"},
    }
    for name, key in ROUTE_CONFIG.items():
        if hasattr(module, name):
            config[key] = getattr(module, name)

    (func_dir / ENTRYPOINT).write_text(
        ENTRYPOINT_SOURCE.format(function=route.function)
    )
    (func_dir / ".vc-config.json").write_text(json.dumps(config, indent=2))


def _write_docs(project_dir: Path, static_dir: Path) -> None:
    """Render the API docs once, at build time, as static files."""
    schema = create_app(project_dir / "app", title=project_dir.name).openapi()
    (static_dir / "openapi.json").write_text(json.dumps(schema))
    html = get_swagger_ui_html(
        openapi_url="/openapi.json", title=schema["info"]["title"]
    )
    (static_dir / "docs.html").write_bytes(bytes(html.body))


def build(
    project_dir: str | Path = ".",
    *,
    python: str = DEFAULT_PYTHON,
    platform: str | None = DEFAULT_PLATFORM,
) -> Path:
    """Build ``project_dir`` into ``.vercel/output`` and return that path.

    Pass ``platform=None`` to vendor dependencies for the current machine,
    which makes the output runnable locally (used by the tests).
    """
    project_dir = Path(project_dir).resolve()
    if not (project_dir / "pyproject.toml").is_file():
        raise FileNotFoundError(f"no pyproject.toml in {project_dir}")
    routes = discover_routes(project_dir / "app")

    output = project_dir / OUTPUT_DIR
    if output.exists():
        shutil.rmtree(output)
    output.mkdir(parents=True)

    # Assemble what every function shares once, then hard-link it into each.
    with tempfile.TemporaryDirectory(dir=output.parent) as tmp:
        shared = Path(tmp) / "shared"
        shutil.copytree(project_dir, shared, ignore=IGNORE)
        (shared / f"{HANDLER_MODULE}.py").write_text(TRAMPOLINE_SOURCE)
        _install_dependencies(project_dir, shared / VENDOR_DIR, python, platform)
        for route in routes:
            _write_function(route, shared, output / "functions", python)

    static_dir = output / "static"
    public_dir = project_dir / "public"
    if public_dir.is_dir():
        shutil.copytree(public_dir, static_dir)
    else:
        static_dir.mkdir()
    _write_docs(project_dir, static_dir)

    # Static files and static-path functions are matched by the filesystem
    # check; only dynamic routes need a rewrite to their function.
    rewrites = [{"src": "^/docs$", "dest": "/docs.html"}]
    rewrites += [
        {"src": route.pattern, "dest": f"/{route.function}"}
        for route in routes
        if route.pattern
    ]
    (output / "config.json").write_text(
        json.dumps(
            {"version": 3, "routes": [{"handle": "filesystem"}, *rewrites]}, indent=2
        )
    )
    return output
