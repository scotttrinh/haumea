"""Emit a Vercel Build Output API (v3) directory for a Haumea project.

    .vercel/output/
    ├── config.json              rewrites for dynamic routes and /docs
    ├── static/                  public/, plus openapi.json and docs.html
    └── functions/
        ├── index.func/                   one function per route.py
        ├── api/hello.func/
        └── api/items/[item_id].func/
            ├── .vc-config.json
            ├── vc__handler__python.py    trampoline into vercel-runtime
            ├── index.py                  exposes this route's ASGI ``app``
            ├── app/ ...                  project source
            └── _vendor/                  dependencies for the target platform

With ``base_path = "/api"`` in ``[tool.haumea]``, function paths, ``static/``
files and rewrites are all prefixed: ``functions/api.func``,
``static/api/docs.html``, ``^/api/docs$``.

Every function carries the same source and dependencies (hard-linked on disk)
and differs only in its entrypoint and ``.vc-config.json``. The function
layout mirrors what Vercel's own Python builder produces.
"""

from __future__ import annotations

import csv
import json
import os
import posixpath
import re
import shutil
import subprocess
import tempfile
import warnings
from collections.abc import Callable, Mapping
from dataclasses import dataclass
from email.parser import HeaderParser
from pathlib import Path

from haumea.config import PYPROJECT, HaumeaConfig, load_config, read_pyproject
from haumea.openapi import swagger_html
from haumea.routing import Route, create_app, discover_routes

OUTPUT_DIR = Path(".vercel") / "output"
UV_LOCK = "uv.lock"
VENDOR_DIR = "_vendor"
HANDLER_MODULE = "vc__handler__python"
ENTRYPOINT = "index.py"

# Vercel's Python functions run on Amazon Linux 2023 (glibc 2.34).
DEFAULT_PLATFORM = "x86_64-manylinux_2_28"
DEFAULT_PYTHON = "3.12"

# Vercel's maximum uncompressed Python function size is 500 MB.
SIZE_WARN_BYTES = 250 * 1024 * 1024
SIZE_LIMIT_BYTES = 500 * 1024 * 1024

IGNORE = shutil.ignore_patterns(
    ".*", "__pycache__", "*.pyc", "public", "node_modules", "tests", "uv.lock"
)

ENTRYPOINT_SOURCE = """\
import os

from haumea import create_route_app

app = create_route_app(
    os.path.join(os.path.dirname(__file__), "app"),
    {function!r},
    base_path={base_path!r},
)
"""

# Module-level settings a route.py may define, and their .vc-config.json keys.
ROUTE_CONFIG = {"max_duration": "maxDuration", "memory": "memory", "regions": "regions"}

# Same contract as the trampoline generated by @vercel/python: point
# vercel-runtime at our entrypoint, put vendored deps on sys.path, hand over.
TRAMPOLINE_SOURCE = f"""\
import importlib
import os
import site
import sys
import time

_here = os.path.dirname(__file__)

os.environ.update({{
    "__VC_PY_BOOT_START_MS": str(int(time.monotonic() * 1000)),
    "__VC_HANDLER_MODULE_NAME": "index",
    "__VC_HANDLER_ENTRYPOINT": "{ENTRYPOINT}",
    "__VC_HANDLER_ENTRYPOINT_ABS": os.path.join(_here, "{ENTRYPOINT}"),
    "__VC_HANDLER_VENDOR_DIR": "{VENDOR_DIR}",
    "__VC_HANDLER_VARIABLE_NAME": "app",
}})

_vendor = os.path.join(_here, "{VENDOR_DIR}")
site.addsitedir(_vendor)
while _vendor in sys.path:
    sys.path.remove(_vendor)
sys.path.insert(1 if sys.path and sys.path[0] in ("", _here) else 0, _vendor)
importlib.invalidate_caches()

from vercel_runtime.vc_init import vc_handler  # noqa: E402,F401
"""


def _is_uv_workspace(directory: Path) -> bool:
    pyproject = directory / PYPROJECT
    if not (directory / UV_LOCK).is_file() or not pyproject.is_file():
        return False
    tool = read_pyproject(pyproject).get("tool")
    if not isinstance(tool, Mapping):
        return False
    uv = tool.get("uv")
    return isinstance(uv, Mapping) and isinstance(uv.get("workspace"), Mapping)


def _find_workspace_root(project_dir: Path) -> Path | None:
    """Nearest directory from ``project_dir`` upward declaring
    ``[tool.uv.workspace]`` alongside ``uv.lock``, or ``None``.

    Stops walking up at any directory with its own ``uv.lock`` that does not
    declare ``[tool.uv.workspace]``.
    """
    for directory in (project_dir, *project_dir.parents):
        if (directory / UV_LOCK).is_file():
            return directory if _is_uv_workspace(directory) else None
    return None


def _project_name(pyproject: Path) -> str | None:
    project = read_pyproject(pyproject).get("project")
    if not isinstance(project, Mapping):
        return None
    name = project.get("name")
    return name if isinstance(name, str) and name.strip() else None


def _run(cmd: list[str], cwd: Path) -> None:
    result = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"`{' '.join(cmd)}` failed:\n{result.stderr}")


def _install_dependencies(
    workspace_root: Path,
    vendor_dir: Path,
    python: str,
    platform: str | None,
    package: str | None = None,
) -> None:
    """Vendor the project's locked dependencies plus Vercel's Python runtime."""
    with tempfile.TemporaryDirectory() as tmp:
        requirements = Path(tmp) / "requirements.txt"
        export = ["uv", "export"]
        if package is not None:
            export += ["--package", package]
        export += [
            "--locked",
            "--no-dev",
            "--no-emit-project",
            "--no-editable",
            "--no-hashes",
            "--quiet",
            "-o",
            str(requirements),
        ]
        _run(export, cwd=workspace_root)
        cmd = [
            "uv",
            "pip",
            "install",
            "--quiet",
            "--target",
            str(vendor_dir),
            "--python-version",
            python,
            "-r",
            str(requirements),
            "vercel-runtime",
        ]
        if platform:
            cmd += ["--python-platform", platform]
        _run(cmd, cwd=workspace_root)


_DIST_NAME_SEP = re.compile(r"[-_.]+")
_REQUIRES_DIST_NAME = re.compile(r"\s*([A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?)")


def normalize_dist_name(name: str) -> str:
    """Normalize a distribution name per PEP 503."""
    return _DIST_NAME_SEP.sub("-", name).lower()


@dataclass(frozen=True)
class Distribution:
    """One installed distribution indexed from a ``*.dist-info`` directory."""

    name: str
    """PEP 503 normalized distribution name."""
    dist_info: str
    """Relative path of the ``*.dist-info`` directory inside the store."""
    files: tuple[str, ...]
    """Relative POSIX paths inside the store listed in ``RECORD``."""
    top_level: frozenset[str]
    """Top-level import names provided by this distribution."""
    requires: frozenset[str]
    """PEP 503 normalized distribution names from ``Requires-Dist`` headers."""
    size: int
    """Total uncompressed size in bytes of this distribution's files."""


@dataclass(frozen=True)
class StoreIndex:
    """Index of every distribution installed in the shared dependency store."""

    distributions: Mapping[str, Distribution]
    """Normalized distribution name -> ``Distribution``."""
    by_import: Mapping[str, tuple[str, ...]]
    """Top-level import name -> sorted normalized distribution names."""


def _parse_requires_dist(value: str) -> str | None:
    """Extract and normalize the distribution name from a ``Requires-Dist`` header."""
    match = _REQUIRES_DIST_NAME.match(value)
    return normalize_dist_name(match.group(1)) if match else None


def _read_record(record_path: Path) -> tuple[str, ...]:
    """Read in-store relative POSIX file paths listed in a ``RECORD`` CSV."""
    if not record_path.is_file():
        return ()
    files: set[str] = set()
    with record_path.open(encoding="utf-8", errors="replace", newline="") as handle:
        for row in csv.reader(handle):
            if not row or not row[0].strip():
                continue
            raw = row[0].replace("\\", "/")
            if raw.startswith("/") or (len(raw) >= 2 and raw[1] == ":"):
                continue
            rel = posixpath.normpath(raw)
            if rel in (".", "..") or rel.startswith("../"):
                continue
            files.add(rel)
    return tuple(sorted(files))


def _top_level_imports(files: tuple[str, ...], dist_info: Path) -> frozenset[str]:
    """Derive top-level import names from ``RECORD`` paths and ``top_level.txt``."""
    names: set[str] = set()
    for rel in files:
        parts = rel.split("/")
        if len(parts) == 1:
            filename = parts[0]
            if filename.endswith(".py"):
                stem = filename[:-3]
                if stem.isidentifier() and stem != "__init__":
                    names.add(stem)
            elif filename.endswith((".so", ".pyd")):
                stem = filename.split(".", 1)[0]
                if stem.isidentifier():
                    names.add(stem)
        else:
            top = parts[0]
            if (
                top == "__pycache__"
                or top.endswith((".dist-info", ".data"))
                or not top.isidentifier()
                or "__pycache__" in parts
            ):
                continue
            if parts[-1].endswith((".py", ".so", ".pyd")):
                names.add(top)

    top_level_txt = dist_info / "top_level.txt"
    if top_level_txt.is_file():
        for line in top_level_txt.read_text(
            encoding="utf-8", errors="replace"
        ).splitlines():
            entry = line.strip()
            if not entry:
                continue
            top = entry.replace("\\", "/").split("/", 1)[0].strip()
            if top.isidentifier():
                names.add(top)

    return frozenset(names)


def _distribution_size(store_dir: Path, dist_info: Path, files: tuple[str, ...]) -> int:
    """Total uncompressed size in bytes of a distribution's files and ``.dist-info``."""
    seen: set[str] = set()
    total = 0
    for rel in files:
        if rel in seen:
            continue
        seen.add(rel)
        target = store_dir / rel
        if target.is_symlink() or target.is_file():
            total += target.lstat().st_size
    for root, _dirs, filenames in os.walk(dist_info, followlinks=False):
        root_path = Path(root)
        for filename in filenames:
            path = root_path / filename
            rel = path.relative_to(store_dir).as_posix()
            if rel in seen:
                continue
            seen.add(rel)
            total += path.lstat().st_size
    return total


def index_store(store_dir: Path) -> StoreIndex:
    """Index every ``*.dist-info`` directory inside ``store_dir``."""
    if not store_dir.is_dir():
        return StoreIndex(distributions={}, by_import={})

    distributions: dict[str, Distribution] = {}
    import_map: dict[str, set[str]] = {}
    parser = HeaderParser()

    for entry in sorted(store_dir.glob("*.dist-info"), key=lambda p: p.name):
        if not entry.is_dir():
            continue
        metadata_path = entry / "METADATA"
        raw_name = entry.name.removesuffix(".dist-info").rsplit("-", 1)[0]
        requires: set[str] = set()
        if metadata_path.is_file():
            headers = parser.parsestr(
                metadata_path.read_text(encoding="utf-8", errors="replace")
            )
            if headers["Name"]:
                raw_name = headers["Name"].strip()
            for req in headers.get_all("Requires-Dist") or ():
                parsed = _parse_requires_dist(req)
                if parsed is not None:
                    requires.add(parsed)

        name = normalize_dist_name(raw_name)
        files = _read_record(entry / "RECORD")
        top_level = _top_level_imports(files, entry)
        size = _distribution_size(store_dir, entry, files)
        distributions[name] = Distribution(
            name=name,
            dist_info=entry.name,
            files=files,
            top_level=top_level,
            requires=frozenset(requires),
            size=size,
        )
        for module in top_level:
            import_map.setdefault(module, set()).add(name)

    sorted_dists = dict(sorted(distributions.items()))
    by_import = {
        module: tuple(sorted(names)) for module, names in sorted(import_map.items())
    }
    return StoreIndex(distributions=sorted_dists, by_import=by_import)


@dataclass(frozen=True)
class FunctionSpec:
    """One Vercel function: a route and everything emitted beside its payload."""

    name: str
    """Function path under ``functions/``, without ``.func``."""
    route: Route
    entrypoint: str
    """Source of the function's ``index.py``."""
    vc_config: dict[str, object]
    """Content of the function's ``.vc-config.json``."""


@dataclass(frozen=True)
class StaticFile:
    """One file generated under ``static/`` at build time."""

    path: str
    """Destination path relative to ``static/``, in POSIX form."""
    content: str


@dataclass(frozen=True)
class BuildPlan:
    """Everything ``build`` will write, decided before touching the output."""

    project_dir: Path
    workspace_root: Path
    package: str | None
    """Workspace package name for ``uv export --package``, or None outside a
    workspace."""
    app_dir: Path
    public_dir: Path | None
    """The project's ``public/`` directory, or None if it has none."""
    output_dir: Path
    config: HaumeaConfig
    """The project's ``[tool.haumea]`` settings."""
    python: str
    platform: str | None
    functions: tuple[FunctionSpec, ...]
    static_files: tuple[StaticFile, ...]
    """Generated files written into ``static/`` over ``public/``."""
    routes: tuple[dict[str, str], ...]
    """The ``routes`` array of ``config.json``."""


def _clone_config(value: object) -> object:
    """Copy nested JSON containers without invoking ``__deepcopy__`` or
    collapsing distinct dict keys like ``1`` and ``"1"``."""
    if isinstance(value, dict):
        return {key: _clone_config(item) for key, item in value.items()}
    if isinstance(value, list):
        return [_clone_config(item) for item in value]
    if isinstance(value, tuple):
        return tuple(_clone_config(item) for item in value)
    return value


def _sort_keys(value: object) -> object:
    """Recursively sort dict keys, keeping mixed key types like ``1`` and ``"1"``
    distinct."""
    if isinstance(value, dict):
        items = [(key, _sort_keys(item)) for key, item in value.items()]
        try:
            items.sort(key=lambda pair: pair[0])
        except TypeError:
            items.sort(key=lambda pair: (str(pair[0]), type(pair[0]).__qualname__))
        return dict(items)
    if isinstance(value, list):
        return [_sort_keys(item) for item in value]
    if isinstance(value, tuple):
        return tuple(_sort_keys(item) for item in value)
    return value


def _dump_json(value: object, *, indent: int | None = None) -> str:
    """Serialize ``value`` with deterministic key ordering."""
    try:
        return json.dumps(value, indent=indent, sort_keys=True)
    except TypeError:
        return json.dumps(_sort_keys(value), indent=indent)


def _plan_function(route: Route, python: str, base_path: str) -> FunctionSpec:
    module = route.load()
    config: dict[str, object] = {
        "runtime": f"python{python}",
        "handler": f"{HANDLER_MODULE}.vc_handler",
        "supportsResponseStreaming": True,
        "environment": {"PYTHONDONTWRITEBYTECODE": "1"},
    }
    for name, key in ROUTE_CONFIG.items():
        if hasattr(module, name):
            config[key] = _clone_config(getattr(module, name))
    return FunctionSpec(
        name=route.function,
        route=route,
        entrypoint=ENTRYPOINT_SOURCE.format(
            function=route.function, base_path=base_path
        ),
        vc_config=config,
    )


def _static_prefix(base_path: str) -> str:
    """Directory under ``static/`` for ``base_path``: ``""`` or ``"api/"``."""
    return f"{base_path.lstrip('/')}/" if base_path else ""


def _plan_static(
    project_dir: Path, app_dir: Path, base_path: str
) -> tuple[StaticFile, ...]:
    """Render the API docs once, at build time, as static files."""
    app = create_app(app_dir, title=project_dir.name, base_path=base_path)
    prefix = _static_prefix(base_path)
    openapi_url = f"{base_path}/openapi.json"
    return (
        StaticFile(f"{prefix}openapi.json", _dump_json(app.openapi())),
        StaticFile(f"{prefix}docs.html", swagger_html(app.title, openapi_url)),
    )


def _plan_routes(routes: list[Route], base_path: str) -> tuple[dict[str, str], ...]:
    # Static files and static-path functions are matched by the filesystem
    # check; only dynamic routes need a rewrite to their function.
    docs = re.escape(f"{base_path}/docs")
    rewrites = [{"src": f"^{docs}$", "dest": f"{base_path}/docs.html"}]
    rewrites += [
        {"src": route.pattern, "dest": f"/{route.function}"}
        for route in routes
        if route.pattern
    ]
    return ({"handle": "filesystem"}, *rewrites)


def _validate_output_dir(
    output_dir: Path, project_dir: Path, app_dir: Path, public_dir: Path | None
) -> None:
    resolved_output = output_dir.resolve()
    if project_dir.resolve().is_relative_to(resolved_output):
        raise ValueError(
            f"output directory cannot contain {project_dir}: {resolved_output}"
        )
    for protected in (app_dir, project_dir / "public", public_dir):
        if protected is None:
            continue
        resolved_protected = protected.resolve()
        if resolved_protected.is_relative_to(
            resolved_output
        ) or resolved_output.is_relative_to(resolved_protected):
            raise ValueError(
                f"output directory cannot overlap {protected}: {resolved_output}"
            )


def _ignore_path(
    target: Path, base: Callable[[str, list[str]], set[str]] | None = None
) -> Callable[[str, list[str]], set[str]]:
    def ignore(src: str, names: list[str]) -> set[str]:
        ignored = set(base(src, names)) if base else set()
        if Path(src).resolve() == target.parent and target.name in names:
            ignored.add(target.name)
        return ignored

    return ignore


def plan_build(
    project_dir: str | Path = ".",
    *,
    python: str = DEFAULT_PYTHON,
    platform: str | None = DEFAULT_PLATFORM,
    output: str | Path | None = None,
) -> BuildPlan:
    """Discover ``project_dir``'s routes and plan its build, leaving the output
    directory untouched.

    Imports every route module, so route code runs now, during planning,
    rather than during emission. Routes are assumed not to modify the
    project's source files at import time: ``emit_build`` copies the project
    and ``public/`` trees as they are when it runs.
    """
    # Discover, before importing any route module.
    project_dir = Path(project_dir).resolve()
    pyproject = project_dir / PYPROJECT
    if not pyproject.is_file():
        raise FileNotFoundError(f"no pyproject.toml in {project_dir}")
    config = load_config(pyproject)
    discovered_workspace = _find_workspace_root(project_dir)
    if discovered_workspace is not None:
        workspace_root = discovered_workspace
        package = _project_name(pyproject)
        if package is None:
            raise ValueError(f"missing [project].name in {pyproject}")
    else:
        workspace_root = project_dir
        package = None
    base_path = config.base_path
    app_dir = project_dir / "app"
    public: Path | None = project_dir / "public"
    if not public.is_dir():
        public = None
    output_dir = (
        Path(output).resolve() if output is not None else project_dir / OUTPUT_DIR
    )
    _validate_output_dir(output_dir, project_dir, app_dir, public)
    routes = discover_routes(app_dir, base_path)

    # Plan.
    return BuildPlan(
        project_dir=project_dir,
        workspace_root=workspace_root,
        package=package,
        app_dir=app_dir,
        public_dir=public,
        output_dir=output_dir,
        config=config,
        python=python,
        platform=platform,
        functions=tuple(_plan_function(route, python, base_path) for route in routes),
        static_files=_plan_static(project_dir, app_dir, base_path),
        routes=_plan_routes(routes, base_path),
    )


@dataclass(frozen=True)
class FunctionReport:
    """Measured uncompressed size and bundled distributions for one function."""

    name: str
    size: int
    distributions: tuple[str, ...]


def _dir_size(directory: Path) -> int:
    """Return the total uncompressed byte size of files under ``directory``."""
    total = 0
    for root, _dirs, files in os.walk(directory, followlinks=False):
        root_path = Path(root)
        for name in files:
            total += (root_path / name).lstat().st_size
    return total


def _format_size(num_bytes: int) -> str:
    """Format a byte count as B, KB, or MB."""
    mb = 1024 * 1024
    if num_bytes >= mb:
        return f"{num_bytes / mb:.1f} MB"
    if num_bytes >= 1024:
        return f"{num_bytes / 1024:.1f} KB"
    return f"{num_bytes} B"


def _format_largest_distributions(
    names: tuple[str, ...], store: StoreIndex, limit: int = 5
) -> str:
    """Format up to ``limit`` largest distributions from ``names``."""
    dists = [store.distributions[name] for name in names if name in store.distributions]
    dists.sort(key=lambda dist: (-dist.size, dist.name))
    return ", ".join(
        f"{dist.name} ({_format_size(dist.size)})" for dist in dists[:limit]
    )


def _report_functions(reports: list[FunctionReport], store: StoreIndex) -> None:
    """Print per-function sizes, warn above ``SIZE_WARN_BYTES``, and fail above
    ``SIZE_LIMIT_BYTES``."""
    if not reports:
        return
    width = max(len(report.name) for report in reports)
    for report in reports:
        count = len(report.distributions)
        unit = "distribution" if count == 1 else "distributions"
        print(f"  {report.name:<{width}}  {_format_size(report.size)} ({count} {unit})")

    oversized: list[str] = []
    for report in reports:
        largest = _format_largest_distributions(report.distributions, store)
        suffix = f" Largest distributions: {largest}" if largest else ""
        if report.size > SIZE_LIMIT_BYTES:
            oversized.append(
                f"Function {report.name!r} bundle is {_format_size(report.size)}, "
                f"exceeding the {_format_size(SIZE_LIMIT_BYTES)} limit.{suffix}"
            )
        elif report.size > SIZE_WARN_BYTES:
            warnings.warn(
                f"Function {report.name!r} bundle is {_format_size(report.size)}, "
                f"exceeding the {_format_size(SIZE_WARN_BYTES)} warning threshold."
                f"{suffix}",
                stacklevel=3,
            )
    if oversized:
        raise RuntimeError("\n".join(oversized))


def _write_function(spec: FunctionSpec, shared: Path, functions_dir: Path) -> Path:
    func_dir = functions_dir / f"{spec.name}.func"
    func_dir.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(shared, func_dir, copy_function=os.link)
    (func_dir / ENTRYPOINT).write_text(spec.entrypoint)
    (func_dir / ".vc-config.json").write_text(_dump_json(spec.vc_config, indent=2))
    return func_dir


def _write_static(plan: BuildPlan, static_dir: Path) -> None:
    """Copy ``public/`` to ``static/<base_path>/``, then write the generated
    files (whose paths already carry the prefix) over it."""
    public_dir = plan.public_dir or (plan.project_dir / "public")
    public_dest = static_dir / _static_prefix(plan.config.base_path)
    if public_dir.is_dir():
        shutil.copytree(
            public_dir,
            public_dest,
            ignore=_ignore_path(plan.output_dir.resolve()),
        )
    else:
        public_dest.mkdir(parents=True)
    for file in plan.static_files:
        dest = static_dir / file.path
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(file.content)


def emit_build(plan: BuildPlan) -> Path:
    """Write ``plan`` to its output directory and return that path."""
    output = plan.output_dir.resolve()
    _validate_output_dir(output, plan.project_dir, plan.app_dir, plan.public_dir)
    if output.exists():
        shutil.rmtree(output)
    output.mkdir(parents=True)

    # Assemble what every function shares once, then hard-link it into each.
    # Keep the staging directory inside output so os.link stays on the same
    # filesystem and copytree excludes both output and staging together.
    with tempfile.TemporaryDirectory(dir=output, prefix=".haumea-") as tmp:
        shared = Path(tmp) / "shared"
        shutil.copytree(plan.project_dir, shared, ignore=_ignore_path(output, IGNORE))
        (shared / f"{HANDLER_MODULE}.py").write_text(TRAMPOLINE_SOURCE)
        vendor_dir = shared / VENDOR_DIR
        _install_dependencies(
            plan.workspace_root,
            vendor_dir,
            plan.python,
            plan.platform,
            plan.package,
        )
        store = index_store(vendor_dir)
        all_distributions = tuple(store.distributions)
        reports: list[FunctionReport] = []
        for spec in plan.functions:
            func_dir = _write_function(spec, shared, output / "functions")
            reports.append(
                FunctionReport(
                    name=spec.name,
                    size=_dir_size(func_dir),
                    distributions=all_distributions,
                )
            )

    _report_functions(reports, store)

    _write_static(plan, output / "static")
    (output / "config.json").write_text(
        _dump_json({"version": 3, "routes": list(plan.routes)}, indent=2)
    )
    return output


def build(
    project_dir: str | Path = ".",
    *,
    python: str = DEFAULT_PYTHON,
    platform: str | None = DEFAULT_PLATFORM,
    output: str | Path | None = None,
) -> Path:
    """Build ``project_dir`` into ``output`` (default ``.vercel/output``) and
    return that path.

    Pass ``platform=None`` to vendor dependencies for the current machine,
    which makes the output runnable locally (used by the tests).
    """
    return emit_build(
        plan_build(project_dir, python=python, platform=platform, output=output)
    )
