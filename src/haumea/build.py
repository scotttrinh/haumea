"""Emit a Vercel Build Output API (v3) directory for a Haumea project.

    .vercel/output/
    ├── config.json              routing: static files first, then the function
    ├── static/                  copy of public/
    └── functions/index.func/
        ├── .vc-config.json
        ├── vc__handler__python.py   trampoline into vercel-runtime
        ├── index.py                 exposes the ASGI ``app``
        ├── app/ ...                 project source
        └── _vendor/                 dependencies, built for the target platform

The whole app is deployed as a single function; the function layout mirrors
what Vercel's own Python builder produces.
"""

from __future__ import annotations

import json
import shutil
import subprocess
import tempfile
from pathlib import Path

OUTPUT_DIR = Path(".vercel") / "output"
VENDOR_DIR = "_vendor"
HANDLER_MODULE = "vc__handler__python"
ENTRYPOINT = "index.py"

# Vercel's Python functions run on Amazon Linux 2023 (glibc 2.34).
DEFAULT_PLATFORM = "x86_64-manylinux_2_28"
DEFAULT_PYTHON = "3.12"

IGNORE = shutil.ignore_patterns(
    ".*", "__pycache__", "*.pyc", "public", "node_modules", "tests", "uv.lock"
)

ENTRYPOINT_SOURCE = """\
import os

from haumea import create_app

app = create_app(os.path.join(os.path.dirname(__file__), "app"))
"""

# Same contract as the trampoline generated by @vercel/python: point
# vercel-runtime at our entrypoint, put vendored deps on sys.path, hand over.
TRAMPOLINE_SOURCE = f"""\
import importlib
import os
import site
import sys
import time

_here = os.path.dirname(__file__)

os.environ.update({{
    "__VC_PY_BOOT_START_MS": str(int(time.monotonic() * 1000)),
    "__VC_HANDLER_MODULE_NAME": "index",
    "__VC_HANDLER_ENTRYPOINT": "{ENTRYPOINT}",
    "__VC_HANDLER_ENTRYPOINT_ABS": os.path.join(_here, "{ENTRYPOINT}"),
    "__VC_HANDLER_VENDOR_DIR": "{VENDOR_DIR}",
    "__VC_HANDLER_VARIABLE_NAME": "app",
}})

_vendor = os.path.join(_here, "{VENDOR_DIR}")
site.addsitedir(_vendor)
while _vendor in sys.path:
    sys.path.remove(_vendor)
sys.path.insert(1 if sys.path and sys.path[0] in ("", _here) else 0, _vendor)
importlib.invalidate_caches()

from vercel_runtime.vc_init import vc_handler  # noqa: E402,F401
"""


def _run(cmd: list[str], cwd: Path) -> None:
    result = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"`{' '.join(cmd)}` failed:\n{result.stderr}")


def _install_dependencies(
    project_dir: Path, vendor_dir: Path, python: str, platform: str | None
) -> None:
    """Vendor the project's locked dependencies plus Vercel's Python runtime."""
    with tempfile.TemporaryDirectory() as tmp:
        requirements = Path(tmp) / "requirements.txt"
        _run(
            [
                "uv",
                "export",
                "--no-dev",
                "--no-emit-project",
                "--no-editable",
                "--no-hashes",
                "--quiet",
                "-o",
                str(requirements),
            ],
            cwd=project_dir,
        )
        cmd = [
            "uv",
            "pip",
            "install",
            "--quiet",
            "--target",
            str(vendor_dir),
            "--python-version",
            python,
            "-r",
            str(requirements),
            "vercel-runtime",
        ]
        if platform:
            cmd += ["--python-platform", platform]
        _run(cmd, cwd=project_dir)


def build(
    project_dir: str | Path = ".",
    *,
    python: str = DEFAULT_PYTHON,
    platform: str | None = DEFAULT_PLATFORM,
) -> Path:
    """Build ``project_dir`` into ``.vercel/output`` and return that path.

    Pass ``platform=None`` to vendor dependencies for the current machine,
    which makes the output runnable locally (used by the tests).
    """
    project_dir = Path(project_dir).resolve()
    if not (project_dir / "app").is_dir():
        raise FileNotFoundError(f"no app/ directory in {project_dir}")
    if not (project_dir / "pyproject.toml").is_file():
        raise FileNotFoundError(f"no pyproject.toml in {project_dir}")

    output = project_dir / OUTPUT_DIR
    if output.exists():
        shutil.rmtree(output)

    func_dir = output / "functions" / "index.func"
    shutil.copytree(project_dir, func_dir, ignore=IGNORE)
    (func_dir / ENTRYPOINT).write_text(ENTRYPOINT_SOURCE)
    (func_dir / f"{HANDLER_MODULE}.py").write_text(TRAMPOLINE_SOURCE)
    (func_dir / ".vc-config.json").write_text(
        json.dumps(
            {
                "runtime": f"python{python}",
                "handler": f"{HANDLER_MODULE}.vc_handler",
                "supportsResponseStreaming": True,
                "environment": {"PYTHONDONTWRITEBYTECODE": "1"},
            },
            indent=2,
        )
    )
    _install_dependencies(project_dir, func_dir / VENDOR_DIR, python, platform)

    static_dir = output / "static"
    public_dir = project_dir / "public"
    if public_dir.is_dir():
        shutil.copytree(public_dir, static_dir)
    else:
        static_dir.mkdir()

    (output / "config.json").write_text(
        json.dumps(
            {
                "version": 3,
                "routes": [
                    {"handle": "filesystem"},
                    {"src": "/(.*)", "dest": "/index"},
                ],
            },
            indent=2,
        )
    )
    return output
