def _clone_config(value: object) -> object:
    """Copy nested JSON containers without invoking ``__deepcopy__`` or
    collapsing distinct dict keys like ``1`` and ``"1"``."""
    if isinstance(value, dict):
        return {key: _clone_config(item) for key, item in value.items()}
    if isinstance(value, list):
        return [_clone_config(item) for item in value]
    if isinstance(value, tuple):
        return tuple(_clone_config(item) for item in value)
    return value


def _sort_keys(value: object) -> object:
    """Recursively sort dict keys, keeping mixed key types like ``1`` and ``"1"``
    distinct."""
    if isinstance(value, dict):
        items = [(key, _sort_keys(item)) for key, item in value.items()]
        try:
            items.sort(key=lambda pair: pair[0])
        except TypeError:
            items.sort(key=lambda pair: (str(pair[0]), type(pair[0]).__qualname__))
        return dict(items)
    if isinstance(value, list):
        return [_sort_keys(item) for item in value]
    if isinstance(value, tuple):
        return tuple(_sort_keys(item) for item in value)
    return value


def _dump_json(value: object, *, indent: int | None = None) -> str:
    """Serialize ``value`` with deterministic key ordering."""
    try:
        return json.dumps(value, indent=indent, sort_keys=True)
    except TypeError:
        return json.dumps(_sort_keys(value), indent=indent)


def _read_route_include(module: ModuleType, route: Route) -> tuple[str, ...]:
    """Read and normalize module-level ``include`` from a loaded route module."""
    if not hasattr(module, "include"):
        return ()
    raw = module.include
    if isinstance(raw, (str, bytes, bytearray)) or not isinstance(raw, Sequence):
        raise ValueError(
            f"invalid `include` in {route.file}: expected a sequence of strings"
        )
    names: list[str] = []
    for item in raw:
        if not isinstance(item, str) or not item.strip():
            raise ValueError(
                f"invalid `include` entry {item!r} in {route.file}: "
                "expected a non-empty string"
            )
        names.append(normalize_dist_name(item.strip()))
    return tuple(dict.fromkeys(names))


def _plan_function(route: Route, python: str, base_path: str) -> FunctionSpec:
    module = route.load()
    config: dict[str, object] = {
        "runtime": f"python{python}",
        "handler": f"{HANDLER_MODULE}.vc_handler",
        "supportsResponseStreaming": True,
        "environment": {"PYTHONDONTWRITEBYTECODE": "1"},
    }
    for name, key in ROUTE_CONFIG.items():
        if hasattr(module, name):
            config[key] = _clone_config(getattr(module, name))
    return FunctionSpec(
        name=route.function,
        route=route,
        entrypoint=ENTRYPOINT_SOURCE.format(
            function=route.function, base_path=base_path
        ),
        vc_config=config,
        trace_roots=(route.file,),
        include=_read_route_include(module, route),
    )


def _static_prefix(base_path: str) -> str:
    """Directory under ``static/`` for ``base_path``: ``""`` or ``"api/"``."""
    return f"{base_path.lstrip('/')}/" if base_path else ""


def _plan_static(
    project_dir: Path, app_dir: Path, base_path: str
) -> tuple[StaticFile, ...]:
    """Render the API docs once, at build time, as static files."""
    app = create_app(app_dir, title=project_dir.name, base_path=base_path)
    prefix = _static_prefix(base_path)
    openapi_url = f"{base_path}/openapi.json"
    return (
        StaticFile(f"{prefix}openapi.json", _dump_json(app.openapi())),
        StaticFile(f"{prefix}docs.html", swagger_html(app.title, openapi_url)),
    )


def _plan_routes(routes: list[Route], base_path: str) -> tuple[dict[str, str], ...]:
    # Static files and static-path functions are matched by the filesystem
    # check; only dynamic routes need a rewrite to their function.
    docs = re.escape(f"{base_path}/docs")
    rewrites = [{"src": f"^{docs}$", "dest": f"{base_path}/docs.html"}]
    rewrites += [
        {"src": route.pattern, "dest": f"/{route.function}"}
        for route in routes
        if route.pattern
    ]
    return ({"handle": "filesystem"}, *rewrites)


def _validate_output_dir(
    output_dir: Path, project_dir: Path, app_dir: Path, public_dir: Path | None
) -> None:
    resolved_output = output_dir.resolve()
    if project_dir.resolve().is_relative_to(resolved_output):
        raise ValueError(
            f"output directory cannot contain {project_dir}: {resolved_output}"
        )
    for protected in (app_dir, project_dir / "public", public_dir):
        if protected is None:
            continue
        resolved_protected = protected.resolve()
        if resolved_protected.is_relative_to(
            resolved_output
        ) or resolved_output.is_relative_to(resolved_protected):
            raise ValueError(
                f"output directory cannot overlap {protected}: {resolved_output}"
            )


def _ignore_path(
    target: Path, base: Callable[[str, list[str]], set[str]] | None = None
) -> Callable[[str, list[str]], set[str]]:
    def ignore(src: str, names: list[str]) -> set[str]:
        ignored = set(base(src, names)) if base else set()
        if Path(src).resolve() == target.parent and target.name in names:
            ignored.add(target.name)
        return ignored

    return ignore


def plan_build(
    project_dir: str | Path = ".",
    *,
    python: str = DEFAULT_PYTHON,
    platform: str | None = DEFAULT_PLATFORM,
    output: str | Path | None = None,
) -> BuildPlan:
    """Discover ``project_dir``'s routes and plan its build, leaving the output
    directory untouched.

    Imports every route module, so route code runs now, during planning,
    rather than during emission. Routes are assumed not to modify the
    project's source files at import time: ``emit_build`` copies the project
    and ``public/`` trees as they are when it runs.
    """
    # Discover, before importing any route module.
    project_dir = Path(project_dir).resolve()
    pyproject = project_dir / PYPROJECT
    if not pyproject.is_file():
        raise FileNotFoundError(f"no pyproject.toml in {project_dir}")
    config = load_config(pyproject)
    discovered_workspace = _find_workspace_root(project_dir)
    if discovered_workspace is not None:
        workspace_root = discovered_workspace
        package = _project_name(pyproject)
        if package is None:
            raise ValueError(f"missing [project].name in {pyproject}")
    else:
        workspace_root = project_dir
        package = None
    base_path = config.base_path
    app_dir = project_dir / "app"
    public: Path | None = project_dir / "public"
    if not public.is_dir():
        public = None
    output_dir = (
        Path(output).resolve() if output is not None else project_dir / OUTPUT_DIR
    )
    _validate_output_dir(output_dir, project_dir, app_dir, public)
    routes = discover_routes(app_dir, base_path)

    # Plan.
    return BuildPlan(
        project_dir=project_dir,
        workspace_root=workspace_root,
        package=package,
        app_dir=app_dir,
        public_dir=public,
        output_dir=output_dir,
        config=config,
        python=python,
        platform=platform,
        functions=tuple(_plan_function(route, python, base_path) for route in routes),
        static_files=_plan_static(project_dir, app_dir, base_path),
        routes=_plan_routes(routes, base_path),
    )


@dataclass(frozen=True)
class FunctionReport:
    """Measured uncompressed size and bundled distributions for one function."""

    name: str
    size: int
    distributions: tuple[str, ...]


def _dir_size(directory: Path) -> int:
    """Return the total uncompressed byte size of files under ``directory``."""
    total = 0
    for root, _dirs, files in os.walk(directory, followlinks=False):
        root_path = Path(root)
        for name in files:
            total += (root_path / name).lstat().st_size
    return total


def _format_size(num_bytes: int) -> str:
    """Format a byte count as B, KB, or MB."""
    mb = 1024 * 1024
    if num_bytes >= mb:
        return f"{num_bytes / mb:.1f} MB"
    if num_bytes >= 1024:
        return f"{num_bytes / 1024:.1f} KB"
    return f"{num_bytes} B"


def _format_largest_distributions(
    names: tuple[str, ...], store: StoreIndex, limit: int = 5
) -> str:
    """Format up to ``limit`` largest distributions from ``names``."""
    dists = [store.distributions[name] for name in names if name in store.distributions]
    dists.sort(key=lambda dist: (-dist.size, dist.name))
    return ", ".join(
        f"{dist.name} ({_format_size(dist.size)})" for dist in dists[:limit]
    )


def _report_functions(reports: list[FunctionReport], store: StoreIndex) -> None:
    """Print per-function sizes, warn above ``SIZE_WARN_BYTES``, and fail above
    ``SIZE_LIMIT_BYTES``."""
    if not reports:
        return
    width = max(len(report.name) for report in reports)
    for report in reports:
        count = len(report.distributions)
        unit = "distribution" if count == 1 else "distributions"
        print(f"  {report.name:<{width}}  {_format_size(report.size)} ({count} {unit})")

    oversized: list[str] = []
    for report in reports:
        largest = _format_largest_distributions(report.distributions, store)
        suffix = f" Largest distributions: {largest}" if largest else ""
        if report.size > SIZE_LIMIT_BYTES:
            oversized.append(
                f"Function {report.name!r} bundle is {_format_size(report.size)}, "
                f"exceeding the {_format_size(SIZE_LIMIT_BYTES)} limit.{suffix}"
            )
        elif report.size > SIZE_WARN_BYTES:
            warnings.warn(
                f"Function {report.name!r} bundle is {_format_size(report.size)}, "
                f"exceeding the {_format_size(SIZE_WARN_BYTES)} warning threshold."
                f"{suffix}",
                stacklevel=3,
            )
    if oversized:
        raise RuntimeError("\n".join(oversized))


@dataclass(frozen=True)
class _ImportRef:
    module: str | None
    level: int
    names: tuple[str, ...] = ()
    package: tuple[str, ...] | None = None


def _is_type_checking_guard(node: ast.expr) -> bool:
    if isinstance(node, ast.Name):
        return node.id == "TYPE_CHECKING"
    if isinstance(node, ast.Attribute):
        return node.attr == "TYPE_CHECKING"
    if isinstance(node, ast.BoolOp) and isinstance(node.op, ast.And):
        return any(_is_type_checking_guard(value) for value in node.values)
    return False


def _call_arg(call: ast.Call, pos: int, kw: str) -> ast.expr | None:
    if pos < len(call.args):
        return call.args[pos]
    for keyword in call.keywords:
        if keyword.arg == kw:
            return keyword.value
    return None


def _str_literal(node: ast.expr | None) -> str | None:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return None


class _ImportCollector(ast.NodeVisitor):
    """Collect runtime imports from one module AST, skipping ``TYPE_CHECKING``."""

    def __init__(self) -> None:
        self.imports: list[_ImportRef] = []
        self.calls: list[ast.Call] = []
        self.importlib_aliases: set[str] = {"importlib"}
        self.import_module_aliases: set[str] = set()
        self.builtins_aliases: set[str] = {"builtins"}
        self.dunder_import_aliases: set[str] = {"__import__"}

    def visit_If(self, node: ast.If) -> None:
        if _is_type_checking_guard(node.test):
            for stmt in node.orelse:
                self.visit(stmt)
            return
        if (
            isinstance(node.test, ast.UnaryOp)
            and isinstance(node.test.op, ast.Not)
            and _is_type_checking_guard(node.test.operand)
        ):
            for stmt in node.body:
                self.visit(stmt)
            return
        self.generic_visit(node)

    def visit_Import(self, node: ast.Import) -> None:
        for alias in node.names:
            self.imports.append(_ImportRef(module=alias.name, level=0))
            if alias.name == "importlib":
                self.importlib_aliases.add(alias.asname or "importlib")
            elif alias.name == "builtins":
                self.builtins_aliases.add(alias.asname or "builtins")

    def visit_ImportFrom(self, node: ast.ImportFrom) -> None:
        names = tuple(alias.name for alias in node.names if alias.name != "*")
        self.imports.append(
            _ImportRef(module=node.module, level=node.level, names=names)
        )
        if node.level == 0 and node.module == "importlib":
            for alias in node.names:
                if alias.name == "import_module":
                    self.import_module_aliases.add(alias.asname or "import_module")
                elif alias.name == "*":
                    self.import_module_aliases.add("import_module")
        elif node.level == 0 and node.module == "builtins":
            for alias in node.names:
                if alias.name == "__import__":
                    self.dunder_import_aliases.add(alias.asname or "__import__")

    def visit_Call(self, node: ast.Call) -> None:
        self.calls.append(node)
        self.generic_visit(node)

    def resolve_calls(self) -> None:
        for call in self.calls:
            func = call.func
            is_import_module = (
                isinstance(func, ast.Attribute)
                and func.attr == "import_module"
                and isinstance(func.value, ast.Name)
                and func.value.id in self.importlib_aliases
            ) or (isinstance(func, ast.Name) and func.id in self.import_module_aliases)
            if is_import_module:
                ref = _parse_import_module_call(call)
                if ref is not None:
                    self.imports.append(ref)
                continue

            is_dunder_import = (
                isinstance(func, ast.Name) and func.id in self.dunder_import_aliases
            ) or (
                isinstance(func, ast.Attribute)
                and func.attr == "__import__"
                and isinstance(func.value, ast.Name)
                and func.value.id in self.builtins_aliases
            )
            if is_dunder_import:
                ref = _parse_dunder_import_call(call)
                if ref is not None:
                    self.imports.append(ref)


def _parse_import_module_call(call: ast.Call) -> _ImportRef | None:
    name = _str_literal(_call_arg(call, 0, "name"))
    if not name:
        return None
    if name.startswith("."):
        level = len(name) - len(name.lstrip("."))
        mod = name[level:] or None
        pkg_arg = _call_arg(call, 1, "package")
        if isinstance(pkg_arg, ast.Name) and pkg_arg.id == "__package__":
            return _ImportRef(module=mod, level=level)
        pkg_str = _str_literal(pkg_arg)
        if pkg_str:
            pkg_parts = tuple(part for part in pkg_str.split(".") if part)
            if pkg_parts:
                return _ImportRef(module=mod, level=level, package=pkg_parts)
        return None
    return _ImportRef(module=name, level=0)


def _parse_dunder_import_call(call: ast.Call) -> _ImportRef | None:
    name = _str_literal(_call_arg(call, 0, "name"))
    if name is None:
        return None
    level_arg = _call_arg(call, 4, "level")
    if level_arg is None:
        level = 0
    elif (
        isinstance(level_arg, ast.Constant)
        and type(level_arg.value) is int
        and level_arg.value >= 0
    ):
        level = level_arg.value
    else:
        return None

    names: tuple[str, ...] = ()
    fromlist_arg = _call_arg(call, 3, "fromlist")
    if isinstance(fromlist_arg, (ast.List, ast.Tuple)):
        names = tuple(
            elt.value
            for elt in fromlist_arg.elts
            if isinstance(elt, ast.Constant)
            and isinstance(elt.value, str)
            and elt.value
            and elt.value != "*"
        )
    if level == 0 and not name:
        return None
    return _ImportRef(module=name or None, level=level, names=names)


def _extract_imports(source: str | bytes, filename: str) -> list[_ImportRef]:
    tree = ast.parse(source, filename=filename)
    collector = _ImportCollector()
    collector.visit(tree)
    collector.resolve_calls()
    return collector.imports


def _package_parts(file_path: Path, project_dir: Path) -> tuple[str, ...]:
    try:
        return file_path.resolve().parent.relative_to(project_dir).parts
    except ValueError:
        return ()


def _resolve_project_modules(parts: tuple[str, ...], project_dir: Path) -> list[Path]:
    """Resolve dotted module ``parts`` to project files inside ``project_dir``,
    including intermediate package ``__init__.py`` files."""
    if not parts or any(
        not part or part in (".", "..") or "/" in part or "\\" in part for part in parts
    ):
        return []
    py_file = project_dir.joinpath(*parts[:-1], f"{parts[-1]}.py")
    init_file = project_dir.joinpath(*parts, "__init__.py")
    if py_file.is_file():
        target = py_file.resolve()
    elif init_file.is_file():
        target = init_file.resolve()
    else:
        return []
    if not target.is_relative_to(project_dir):
        return []

    files: list[Path] = []
    for i in range(1, len(parts)):
        parent_init = project_dir.joinpath(*parts[:i], "__init__.py")
        if parent_init.is_file():
            resolved_parent = parent_init.resolve()
            if resolved_parent.is_relative_to(project_dir):
                files.append(resolved_parent)
    files.append(target)
    return files


def _resolve_import_ref(
    ref: _ImportRef,
    current_package: tuple[str, ...],
    project_dir: Path,
    store: StoreIndex,
) -> tuple[list[Path], tuple[str, ...]]:
    """Resolve one ``_ImportRef`` to project files to recurse into and/or
    distribution names from ``store``."""
    mod_parts = (
        tuple(part for part in ref.module.split(".") if part) if ref.module else ()
    )
    if ref.level > 0:
        base_pkg = ref.package if ref.package is not None else current_package
        up = ref.level - 1
        if up > len(base_pkg):
            return [], ()
        target_parts = (*base_pkg[: len(base_pkg) - up], *mod_parts)
        allow_store = ref.package is not None
    else:
        if not mod_parts:
            return [], ()
        target_parts = mod_parts
        allow_store = True

    project_files: list[Path] = []
    if target_parts:
        project_files.extend(_resolve_project_modules(target_parts, project_dir))
    for name in ref.names:
        project_files.extend(
            _resolve_project_modules((*target_parts, name), project_dir)
        )
    if project_files or not allow_store or not target_parts:
        return project_files, ()
    top = target_parts[0]
    if top in sys.stdlib_module_names:
        return [], ()
    return [], store.by_import.get(top, ())


def trace_function(
    spec: FunctionSpec, project_dir: Path, store: StoreIndex
) -> frozenset[str]:
    """Statically trace ``spec.trace_roots`` and ``spec.entrypoint``, following
    project modules recursively and returning matched distribution names."""
    project_root = project_dir.resolve()
    visited: set[Path] = set()
    queue: deque[Path] = deque()
    distributions: set[str] = set()

    def enqueue_files(paths: Iterable[Path]) -> None:
        for path in paths:
            resolved = path.resolve()
            if resolved not in visited and resolved.is_file():
                visited.add(resolved)
                queue.append(resolved)

    def process_refs(refs: list[_ImportRef], current_package: tuple[str, ...]) -> None:
        for ref in refs:
            files, dists = _resolve_import_ref(
                ref, current_package, project_root, store
            )
            enqueue_files(files)
            distributions.update(dists)

    # Trace generated entrypoint (imports haumea) plus every file trace root.
    process_refs(_extract_imports(spec.entrypoint, str(project_root / ENTRYPOINT)), ())
    enqueue_files(spec.trace_roots)

    while queue:
        current = queue.popleft()
        package = _package_parts(current, project_root)
        process_refs(_extract_imports(current.read_bytes(), str(current)), package)

    return frozenset(distributions)


def resolve_closure(seeds: Iterable[str], store: StoreIndex) -> tuple[str, ...]:
    """Return the sorted transitive closure of ``seeds`` over ``Requires-Dist``
    for distributions present in ``store``."""
    included: set[str] = set()
    queue: deque[str] = deque()
    for raw in seeds:
        name = normalize_dist_name(raw)
        if name in store.distributions and name not in included:
            included.add(name)
            queue.append(name)
    while queue:
        current = queue.popleft()
        for req in store.distributions[current].requires:
            if req in store.distributions and req not in included:
                included.add(req)
                queue.append(req)
    return tuple(sorted(included))


def resolve_distributions(
    spec: FunctionSpec,
    project_dir: Path,
    config: HaumeaConfig,
    store: StoreIndex,
) -> tuple[str, ...]:
    """Compute the final sorted distributions to bundle for ``spec``."""
    seeds = (
        *trace_function(spec, project_dir, store),
        *ALWAYS_INCLUDED,
        *config.include,
        *spec.include,
    )
    return resolve_closure(seeds, store)


def _link_distributions(
    store_dir: Path,
    vendor_dest: Path,
    distributions: tuple[str, ...],
    store: StoreIndex,
) -> None:
    """Hard-link every ``RECORD`` file and ``.dist-info`` directory for
    ``distributions`` from ``store_dir`` into ``vendor_dest``."""
    if not store_dir.is_dir():
        return
    vendor_dest.mkdir(parents=True, exist_ok=True)
    linked: set[str] = set()

    def link_file(rel: str) -> None:
        if rel in linked:
            return
        src = store_dir / rel
        if src.is_symlink():
            dest = vendor_dest / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            os.symlink(os.readlink(src), dest)
            linked.add(rel)
        elif src.is_file():
            dest = vendor_dest / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            os.link(src, dest)
            linked.add(rel)

    for name in distributions:
        dist = store.distributions.get(name)
        if dist is None:
            continue
        for rel in dist.files:
            link_file(rel)
        dist_info_dir = store_dir / dist.dist_info
        if dist_info_dir.is_dir():
            for root, _dirs, filenames in os.walk(dist_info_dir, followlinks=False):
                root_path = Path(root)
                for filename in filenames:
                    rel = (root_path / filename).relative_to(store_dir).as_posix()
                    link_file(rel)


def _write_function(spec: FunctionSpec, shared: Path, functions_dir: Path) -> Path:
    func_dir = functions_dir / f"{spec.name}.func"
    func_dir.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(shared, func_dir, copy_function=os.link)
    (func_dir / ENTRYPOINT).write_text(spec.entrypoint)
    (func_dir / ".vc-config.json").write_text(_dump_json(spec.vc_config, indent=2))
    return func_dir


def _write_static(plan: BuildPlan, static_dir: Path) -> None:
    """Copy ``public/`` to ``static/<base_path>/``, then write the generated
    files (whose paths already carry the prefix) over it."""
    public_dir = plan.public_dir or (plan.project_dir / "public")
    public_dest = static_dir / _static_prefix(plan.config.base_path)
    if public_dir.is_dir():
        shutil.copytree(
            public_dir,
            public_dest,
            ignore=_ignore_path(plan.output_dir.resolve()),
        )
    else:
        public_dest.mkdir(parents=True)
    for file in plan.static_files:
        dest = static_dir / file.path
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(file.content)


def emit_build(plan: BuildPlan) -> Path:
    """Write ``plan`` to its output directory and return that path."""
    output = plan.output_dir.resolve()
    _validate_output_dir(output, plan.project_dir, plan.app_dir, plan.public_dir)
    if output.exists():
        shutil.rmtree(output)
    output.mkdir(parents=True)

    # Assemble shared project source and the dependency store once, then
    # hard-link each function's files from them. Keep the staging directory
    # inside output so os.link stays on the same filesystem and copytree
    # excludes both output and staging together.
    with tempfile.TemporaryDirectory(dir=output, prefix=".haumea-") as tmp:
        shared = Path(tmp) / "shared"
        shutil.copytree(plan.project_dir, shared, ignore=_ignore_path(output, IGNORE))
        (shared / f"{HANDLER_MODULE}.py").write_text(TRAMPOLINE_SOURCE)
        store_dir = Path(tmp) / "store"
        _install_dependencies(
            plan.workspace_root,
            store_dir,
            plan.python,
            plan.platform,
            plan.package,
        )
        store = index_store(store_dir)
        all_distributions = tuple(store.distributions)
        reports: list[FunctionReport] = []
        for spec in plan.functions:
            func_dir = _write_function(spec, shared, output / "functions")
            vendor_dest = func_dir / VENDOR_DIR
            if plan.config.tree_shake:
                distributions = resolve_distributions(
                    spec, plan.project_dir, plan.config, store
                )
                _link_distributions(store_dir, vendor_dest, distributions, store)
            else:
                distributions = all_distributions
                if store_dir.is_dir():
                    shutil.copytree(
                        store_dir,
                        vendor_dest,
                        copy_function=os.link,
                        dirs_exist_ok=True,
                    )
            reports.append(
                FunctionReport(
                    name=spec.name,
                    size=_dir_size(func_dir),
                    distributions=distributions,
                )
            )

    _report_functions(reports, store)

    _write_static(plan, output / "static")
    (output / "config.json").write_text(
        _dump_json({"version": 3, "routes": list(plan.routes)}, indent=2)
    )
    return output


def build(
    project_dir: str | Path = ".",
    *,
    python: str = DEFAULT_PYTHON,
    platform: str | None = DEFAULT_PLATFORM,
    output: str | Path | None = None,
) -> Path:
    """Build ``project_dir`` into ``output`` (default ``.vercel/output``) and
    return that path.

    Pass ``platform=None`` to vendor dependencies for the current machine,
    which makes the output runnable locally (used by the tests).
    """
    return emit_build(
        plan_build(project_dir, python=python, platform=platform, output=output)
    )
