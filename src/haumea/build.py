"""Emit a Vercel Build Output API (v3) directory for a Haumea project.

    .vercel/output/
    ├── config.json              rewrites for dynamic routes and /docs
    ├── static/                  public/, plus openapi.json and docs.html
    └── functions/
        ├── index.func/                   one function per route.py
        ├── api/hello.func/
        └── api/items/[item_id].func/
            ├── .vc-config.json
            ├── vc__handler__python.py    trampoline into vercel-runtime
            ├── index.py                  exposes this route's ASGI ``app``
            ├── app/ ...                  project source
            └── _vendor/                  dependencies for the target platform

With ``base_path = "/api"`` in ``[tool.haumea]``, function paths, ``static/``
files and rewrites are all prefixed: ``functions/api.func``,
``static/api/docs.html``, ``^/api/docs$``.

Every function carries the same source and dependencies (hard-linked on disk)
and differs only in its entrypoint and ``.vc-config.json``. The function
layout mirrors what Vercel's own Python builder produces.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import tempfile
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

from haumea.config import PYPROJECT, HaumeaConfig, load_config
from haumea.openapi import swagger_html
from haumea.routing import Route, create_app, discover_routes

OUTPUT_DIR = Path(".vercel") / "output"
VENDOR_DIR = "_vendor"
HANDLER_MODULE = "vc__handler__python"
ENTRYPOINT = "index.py"

# Vercel's Python functions run on Amazon Linux 2023 (glibc 2.34).
DEFAULT_PLATFORM = "x86_64-manylinux_2_28"
DEFAULT_PYTHON = "3.12"

IGNORE = shutil.ignore_patterns(
    ".*", "__pycache__", "*.pyc", "public", "node_modules", "tests", "uv.lock"
)

ENTRYPOINT_SOURCE = """\
import os

from haumea import create_route_app

app = create_route_app(
    os.path.join(os.path.dirname(__file__), "app"),
    {function!r},
    base_path={base_path!r},
)
"""

# Module-level settings a route.py may define, and their .vc-config.json keys.
ROUTE_CONFIG = {"max_duration": "maxDuration", "memory": "memory", "regions": "regions"}

# Same contract as the trampoline generated by @vercel/python: point
# vercel-runtime at our entrypoint, put vendored deps on sys.path, hand over.
TRAMPOLINE_SOURCE = f"""\
import importlib
import os
import site
import sys
import time

_here = os.path.dirname(__file__)

os.environ.update({{
    "__VC_PY_BOOT_START_MS": str(int(time.monotonic() * 1000)),
    "__VC_HANDLER_MODULE_NAME": "index",
    "__VC_HANDLER_ENTRYPOINT": "{ENTRYPOINT}",
    "__VC_HANDLER_ENTRYPOINT_ABS": os.path.join(_here, "{ENTRYPOINT}"),
    "__VC_HANDLER_VENDOR_DIR": "{VENDOR_DIR}",
    "__VC_HANDLER_VARIABLE_NAME": "app",
}})

_vendor = os.path.join(_here, "{VENDOR_DIR}")
site.addsitedir(_vendor)
while _vendor in sys.path:
    sys.path.remove(_vendor)
sys.path.insert(1 if sys.path and sys.path[0] in ("", _here) else 0, _vendor)
importlib.invalidate_caches()

from vercel_runtime.vc_init import vc_handler  # noqa: E402,F401
"""


def _run(cmd: list[str], cwd: Path) -> None:
    result = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"`{' '.join(cmd)}` failed:\n{result.stderr}")


def _install_dependencies(
    project_dir: Path, vendor_dir: Path, python: str, platform: str | None
) -> None:
    """Vendor the project's locked dependencies plus Vercel's Python runtime."""
    with tempfile.TemporaryDirectory() as tmp:
        requirements = Path(tmp) / "requirements.txt"
        _run(
            [
                "uv",
                "export",
                "--locked",
                "--no-dev",
                "--no-emit-project",
                "--no-editable",
                "--no-hashes",
                "--quiet",
                "-o",
                str(requirements),
            ],
            cwd=project_dir,
        )
        cmd = [
            "uv",
            "pip",
            "install",
            "--quiet",
            "--target",
            str(vendor_dir),
            "--python-version",
            python,
            "-r",
            str(requirements),
            "vercel-runtime",
        ]
        if platform:
            cmd += ["--python-platform", platform]
        _run(cmd, cwd=project_dir)


@dataclass(frozen=True)
class FunctionSpec:
    """One Vercel function: a route and everything emitted beside its payload."""

    name: str
    """Function path under ``functions/``, without ``.func``."""
    route: Route
    entrypoint: str
    """Source of the function's ``index.py``."""
    vc_config: dict[str, object]
    """Content of the function's ``.vc-config.json``."""


@dataclass(frozen=True)
class StaticFile:
    """One file generated under ``static/`` at build time."""

    path: str
    """Destination path relative to ``static/``, in POSIX form."""
    content: str


@dataclass(frozen=True)
class BuildPlan:
    """Everything ``build`` will write, decided before touching the output."""

    project_dir: Path
    workspace_root: Path
    app_dir: Path
    public_dir: Path | None
    """The project's ``public/`` directory, or None if it has none."""
    output_dir: Path
    config: HaumeaConfig
    """The project's ``[tool.haumea]`` settings."""
    python: str
    platform: str | None
    functions: tuple[FunctionSpec, ...]
    static_files: tuple[StaticFile, ...]
    """Generated files written into ``static/`` over ``public/``."""
    routes: tuple[dict[str, str], ...]
    """The ``routes`` array of ``config.json``."""


def _clone_config(value: object) -> object:
    """Copy nested JSON containers without invoking ``__deepcopy__`` or
    collapsing distinct dict keys like ``1`` and ``"1"``."""
    if isinstance(value, dict):
        return {key: _clone_config(item) for key, item in value.items()}
    if isinstance(value, list):
        return [_clone_config(item) for item in value]
    if isinstance(value, tuple):
        return tuple(_clone_config(item) for item in value)
    return value


def _sort_keys(value: object) -> object:
    """Recursively sort dict keys, keeping mixed key types like ``1`` and ``"1"``
    distinct."""
    if isinstance(value, dict):
        items = [(key, _sort_keys(item)) for key, item in value.items()]
        try:
            items.sort(key=lambda pair: pair[0])
        except TypeError:
            items.sort(key=lambda pair: (str(pair[0]), type(pair[0]).__qualname__))
        return dict(items)
    if isinstance(value, list):
        return [_sort_keys(item) for item in value]
    if isinstance(value, tuple):
        return tuple(_sort_keys(item) for item in value)
    return value


def _dump_json(value: object, *, indent: int | None = None) -> str:
    """Serialize ``value`` with deterministic key ordering."""
    try:
        return json.dumps(value, indent=indent, sort_keys=True)
    except TypeError:
        return json.dumps(_sort_keys(value), indent=indent)


def _plan_function(route: Route, python: str, base_path: str) -> FunctionSpec:
    module = route.load()
    config: dict[str, object] = {
        "runtime": f"python{python}",
        "handler": f"{HANDLER_MODULE}.vc_handler",
        "supportsResponseStreaming": True,
        "environment": {"PYTHONDONTWRITEBYTECODE": "1"},
    }
    for name, key in ROUTE_CONFIG.items():
        if hasattr(module, name):
            config[key] = _clone_config(getattr(module, name))
    return FunctionSpec(
        name=route.function,
        route=route,
        entrypoint=ENTRYPOINT_SOURCE.format(
            function=route.function, base_path=base_path
        ),
        vc_config=config,
    )


def _static_prefix(base_path: str) -> str:
    """Directory under ``static/`` for ``base_path``: ``""`` or ``"api/"``."""
    return f"{base_path.lstrip('/')}/" if base_path else ""


def _plan_static(
    project_dir: Path, app_dir: Path, base_path: str
) -> tuple[StaticFile, ...]:
    """Render the API docs once, at build time, as static files."""
    app = create_app(app_dir, title=project_dir.name, base_path=base_path)
    prefix = _static_prefix(base_path)
    openapi_url = f"{base_path}/openapi.json"
    return (
        StaticFile(f"{prefix}openapi.json", _dump_json(app.openapi())),
        StaticFile(f"{prefix}docs.html", swagger_html(app.title, openapi_url)),
    )


def _plan_routes(routes: list[Route], base_path: str) -> tuple[dict[str, str], ...]:
    # Static files and static-path functions are matched by the filesystem
    # check; only dynamic routes need a rewrite to their function.
    docs = re.escape(f"{base_path}/docs")
    rewrites = [{"src": f"^{docs}$", "dest": f"{base_path}/docs.html"}]
    rewrites += [
        {"src": route.pattern, "dest": f"/{route.function}"}
        for route in routes
        if route.pattern
    ]
    return ({"handle": "filesystem"}, *rewrites)


def _validate_output_dir(
    output_dir: Path, project_dir: Path, app_dir: Path, public_dir: Path | None
) -> None:
    resolved_output = output_dir.resolve()
    if project_dir.resolve().is_relative_to(resolved_output):
        raise ValueError(
            f"output directory cannot contain {project_dir}: {resolved_output}"
        )
    for protected in (app_dir, project_dir / "public", public_dir):
        if protected is None:
            continue
        resolved_protected = protected.resolve()
        if resolved_protected.is_relative_to(
            resolved_output
        ) or resolved_output.is_relative_to(resolved_protected):
            raise ValueError(
                f"output directory cannot overlap {protected}: {resolved_output}"
            )


def _ignore_path(
    target: Path, base: Callable[[str, list[str]], set[str]] | None = None
) -> Callable[[str, list[str]], set[str]]:
    def ignore(src: str, names: list[str]) -> set[str]:
        ignored = set(base(src, names)) if base else set()
        if Path(src).resolve() == target.parent and target.name in names:
            ignored.add(target.name)
        return ignored

    return ignore


def plan_build(
    project_dir: str | Path = ".",
    *,
    python: str = DEFAULT_PYTHON,
    platform: str | None = DEFAULT_PLATFORM,
    output: str | Path | None = None,
) -> BuildPlan:
    """Discover ``project_dir``'s routes and plan its build, leaving the output
    directory untouched.

    Imports every route module, so route code runs now, during planning,
    rather than during emission. Routes are assumed not to modify the
    project's source files at import time: ``emit_build`` copies the project
    and ``public/`` trees as they are when it runs.
    """
    # Discover, before importing any route module.
    project_dir = Path(project_dir).resolve()
    pyproject = project_dir / PYPROJECT
    if not pyproject.is_file():
        raise FileNotFoundError(f"no pyproject.toml in {project_dir}")
    config = load_config(pyproject)
    base_path = config.base_path
    app_dir = project_dir / "app"
    public: Path | None = project_dir / "public"
    if not public.is_dir():
        public = None
    output_dir = (
        Path(output).resolve() if output is not None else project_dir / OUTPUT_DIR
    )
    _validate_output_dir(output_dir, project_dir, app_dir, public)
    routes = discover_routes(app_dir, base_path)

    # Plan.
    return BuildPlan(
        project_dir=project_dir,
        workspace_root=project_dir,
        app_dir=app_dir,
        public_dir=public,
        output_dir=output_dir,
        config=config,
        python=python,
        platform=platform,
        functions=tuple(_plan_function(route, python, base_path) for route in routes),
        static_files=_plan_static(project_dir, app_dir, base_path),
        routes=_plan_routes(routes, base_path),
    )


def _write_function(spec: FunctionSpec, shared: Path, functions_dir: Path) -> None:
    func_dir = functions_dir / f"{spec.name}.func"
    func_dir.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(shared, func_dir, copy_function=os.link)
    (func_dir / ENTRYPOINT).write_text(spec.entrypoint)
    (func_dir / ".vc-config.json").write_text(_dump_json(spec.vc_config, indent=2))


def _write_static(plan: BuildPlan, static_dir: Path) -> None:
    """Copy ``public/`` to ``static/<base_path>/``, then write the generated
    files (whose paths already carry the prefix) over it."""
    public_dir = plan.public_dir or (plan.project_dir / "public")
    public_dest = static_dir / _static_prefix(plan.config.base_path)
    if public_dir.is_dir():
        shutil.copytree(
            public_dir,
            public_dest,
            ignore=_ignore_path(plan.output_dir.resolve()),
        )
    else:
        public_dest.mkdir(parents=True)
    for file in plan.static_files:
        dest = static_dir / file.path
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(file.content)


def emit_build(plan: BuildPlan) -> Path:
    """Write ``plan`` to its output directory and return that path."""
    output = plan.output_dir.resolve()
    _validate_output_dir(output, plan.project_dir, plan.app_dir, plan.public_dir)
    if output.exists():
        shutil.rmtree(output)
    output.mkdir(parents=True)

    # Assemble what every function shares once, then hard-link it into each.
    # Keep the staging directory inside output so os.link stays on the same
    # filesystem and copytree excludes both output and staging together.
    with tempfile.TemporaryDirectory(dir=output, prefix=".haumea-") as tmp:
        shared = Path(tmp) / "shared"
        shutil.copytree(plan.project_dir, shared, ignore=_ignore_path(output, IGNORE))
        (shared / f"{HANDLER_MODULE}.py").write_text(TRAMPOLINE_SOURCE)
        _install_dependencies(
            plan.project_dir, shared / VENDOR_DIR, plan.python, plan.platform
        )
        for spec in plan.functions:
            _write_function(spec, shared, output / "functions")

    _write_static(plan, output / "static")
    (output / "config.json").write_text(
        _dump_json({"version": 3, "routes": list(plan.routes)}, indent=2)
    )
    return output


def build(
    project_dir: str | Path = ".",
    *,
    python: str = DEFAULT_PYTHON,
    platform: str | None = DEFAULT_PLATFORM,
    output: str | Path | None = None,
) -> Path:
    """Build ``project_dir`` into ``output`` (default ``.vercel/output``) and
    return that path.

    Pass ``platform=None`` to vendor dependencies for the current machine,
    which makes the output runnable locally (used by the tests).
    """
    return emit_build(
        plan_build(project_dir, python=python, platform=platform, output=output)
    )
